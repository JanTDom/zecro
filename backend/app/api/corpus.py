router = APIRouter(prefix="/projects", tags=["corpus"])

SUPPORTED_EXTENSIONS = {
    ".pdf": "pdf",
    ".idml": "idml",
    ".png": "image",
    ".jpg": "image",
    ".jpeg": "image",
    ".webp": "image",
    ".tiff": "image",
    ".tif": "image",
    ".svg": "image"
}

class DirectoryImportRequest(BaseModel):
    directory_path: str
    recursive: bool = True

def extract_features_from_file(file_path: Path, file_type: str) -> dict:
    """
    Extract geometric, typographic and photo/text features from a real page.

    ``file_type`` is kept in the public signature for callers of the original
    importer.  The extractor determines the concrete format from the path and
    safely falls back to deterministic format priors for malformed PDFs/IDML.
    """
    return extract_page_features(file_path)


def _api_features(features: dict, path: Path, project_id: str, page_id: str) -> dict:
    """Add storage/UI aliases while keeping the measured feature record intact."""
    enriched = dict(features)
    enriched.update({
        "file_size_bytes": path.stat().st_size if path.exists() else 0,
        "page_number": 1,
        "width_mm": features.get("trim_w_mm", 280.0),
        "height_mm": features.get("trim_h_mm", 400.0),
        "thumbnail_url": f"/projects/{project_id}/corpus/{page_id}/thumbnail",
        "preview_url": f"/projects/{project_id}/corpus/{page_id}/file",
        "bounding_boxes": features.get("bounding_boxes", []),
        "whitespace_ratio": round(max(0.0, 1.0 - (float(features.get("photo_coverage_pct", 0.0)) + float(features.get("text_coverage_pct", 0.0))) / 100.0), 4),
        "detected_columns": features.get("columns", features.get("dominant_columns", 0)),
        "body_font_size_pt": features.get("body_size_pt", 0),
        "max_headline_size_pt": round(float(features.get("body_size_pt", 0)) * float(features.get("headline_scale_ratio", 0)), 2),
    })
    return enriched

@router.get("/{project_id}/corpus", response_model=List[CorpusPage])
def list_corpus_pages(project_id: str):
    proj = db.get_project(project_id)
    if not proj:
        raise HTTPException(status_code=404, detail="Project not found")
    return db.list_corpus_pages(project_id)


def _owned_corpus_page(project_id: str, page_id: str, *, require_file: bool = True):
    if not db.get_project(project_id):
        raise HTTPException(status_code=404, detail="Project not found")
    page = db.get_corpus_page(project_id, page_id)
    if not page:
        raise HTTPException(status_code=404, detail="Corpus page not found")
    path = Path(page.file_path).resolve()
    # Database paths are generated by this API/importer.  The existence check
    # also handles pages whose source was manually removed.
    if require_file and not path.is_file():
        raise HTTPException(status_code=404, detail="Corpus asset is missing")
    return page, path


@router.get("/{project_id}/corpus/{page_id}/file", include_in_schema=False)
def get_corpus_file(project_id: str, page_id: str):
    page, path = _owned_corpus_page(project_id, page_id)
    return FileResponse(path, media_type={"pdf": "application/pdf", "idml": "application/zip", "image": "image/*"}.get(page.file_type, "application/octet-stream"), filename=path.name)


@router.get("/{project_id}/corpus/{page_id}/thumbnail", include_in_schema=False)
def get_corpus_thumbnail(project_id: str, page_id: str):
    page, path = _owned_corpus_page(project_id, page_id)
    if page.file_type == "image":
        # Browser-side object-fit gives a consistent crop; serving the source
        # avoids a second copy of potentially large uploaded photos.
        return FileResponse(path, media_type="image/*", filename=path.name)
    # Convert the first PDF page lazily and cache it under managed storage.
    thumb_dir = settings.thumbnails_dir
    thumb_dir.mkdir(parents=True, exist_ok=True)
    thumb = thumb_dir / f"corpus_{page.id}.png"
    if not thumb.exists() and page.file_type == "pdf":
        prefix = thumb.with_suffix("")
        try:
            subprocess.run(["pdftoppm", "-f", "1", "-singlefile", "-png", "-scale-to", "600", str(path), str(prefix)], check=True, capture_output=True, timeout=20)
        except (OSError, subprocess.SubprocessError):
            # A malformed/uploaded sample can still be previewed as a PDF by
            # the browser; keep the endpoint useful instead of returning 500.
            return FileResponse(path, media_type="application/pdf", filename=path.name)
    if thumb.exists():
        return FileResponse(thumb, media_type="image/png", filename=thumb.name)
    return FileResponse(path, media_type="application/octet-stream", filename=path.name)


@router.delete("/{project_id}/corpus/{page_id}", status_code=status.HTTP_204_NO_CONTENT)
def delete_corpus_page(project_id: str, page_id: str):
    page, path = _owned_corpus_page(project_id, page_id, require_file=False)
    if not db.delete_corpus_page(project_id, page_id):
        raise HTTPException(status_code=404, detail="Corpus page not found")
    try:
        path.unlink(missing_ok=True)
        (settings.thumbnails_dir / f"corpus_{page_id}.png").unlink(missing_ok=True)
    except OSError:
        # Metadata deletion succeeded; stale files are harmless and can be
        # cleaned up by the storage maintenance command.
        pass
    return None

@router.post("/{project_id}/corpus", response_model=CorpusPage, status_code=status.HTTP_201_CREATED)
@router.post("/{project_id}/corpus/upload", response_model=CorpusPage, status_code=status.HTTP_201_CREATED, include_in_schema=False)
async def upload_corpus_page(
    project_id: str,
    title: str = Form("Imported editorial page"),
    file: UploadFile = File(...)
):
    proj = db.get_project(project_id)
    if not proj:
        raise HTTPException(status_code=404, detail="Project not found")

    ext = Path(file.filename).suffix.lower()
    file_type = SUPPORTED_EXTENSIONS.get(ext, "image")
    file_id = str(uuid.uuid4())
    saved_filename = f"corpus_{project_id}_{file_id}{ext}"
    saved_path = settings.UPLOADS_DIR / saved_filename

    settings.UPLOADS_DIR.mkdir(parents=True, exist_ok=True)
    with open(saved_path, "wb") as buffer:
        shutil.copyfileobj(file.file, buffer)

    features = _api_features(extract_features_from_file(saved_path, file_type), saved_path, project_id, file_id)

    corpus_page = CorpusPage(
        id=file_id,
        project_id=project_id,
        title=title,
        file_path=str(saved_path),
        file_type=file_type,
        extracted_features=features
    )
    return db.add_corpus_page(corpus_page)

@router.post("/{project_id}/corpus/directory", response_model=List[CorpusPage], status_code=status.HTTP_201_CREATED)
def import_corpus_directory(
    project_id: str,
    body: DirectoryImportRequest
):
    """
    Imports all supported layout files from a local directory into the project's corpus.
    """
    proj = db.get_project(project_id)
    if not proj:
        raise HTTPException(status_code=404, detail="Project not found")

    dir_path = Path(body.directory_path).resolve()
    if not dir_path.exists() or not dir_path.is_dir():
        raise HTTPException(status_code=400, detail=f"Directory '{dir_path}' does not exist or is not a directory.")

    settings.UPLOADS_DIR.mkdir(parents=True, exist_ok=True)
    pattern = "**/*" if body.recursive else "*"
    imported: List[CorpusPage] = []

    for file_path in dir_path.glob(pattern):
        if file_path.is_file() and file_path.suffix.lower() in SUPPORTED_EXTENSIONS:
            ext = file_path.suffix.lower()
            file_type = SUPPORTED_EXTENSIONS[ext]
            file_id = str(uuid.uuid4())
            saved_filename = f"corpus_{project_id}_{file_id}{ext}"
            saved_path = settings.UPLOADS_DIR / saved_filename

            shutil.copy2(file_path, saved_path)
            features = _api_features(extract_features_from_file(saved_path, file_type), saved_path, project_id, file_id)

            page_title = file_path.stem.replace("-", " ").replace("_", " ").title()
            corpus_page = CorpusPage(
                id=file_id,
                project_id=project_id,
                title=page_title,
                file_path=str(saved_path),
                file_type=file_type,
                extracted_features=features
            )
            db.add_corpus_page(corpus_page)
            imported.append(corpus_page)

    if imported:
        learn_dna_from_corpus(project_id)

    return imported

@router.post("/{project_id}/dna:learn", response_model=TitleDNA)
@router.post("/{project_id}/dna/learn", response_model=TitleDNA, include_in_schema=False)
def learn_dna_from_corpus(project_id: str):
    """
    Learns and refines the TitleDNA based on all uploaded corpus pages.
    """
    proj = db.get_project(project_id)
    if not proj:
        raise HTTPException(status_code=404, detail="Project not found")

    corpus = db.list_corpus_pages(project_id)
    dna = db.get_title_dna(project_id)
    if not dna:
        raise HTTPException(status_code=404, detail="Title DNA not found")

    if corpus:
        features = [c.extracted_features for c in corpus if c.extracted_features]
        avg_trans = sum(c.get("avg_transgressions_per_page", 1.0) for c in features) / max(1, len(features))
        dna.page_energy_budget = round(max(0.4, min(1.5, avg_trans * 0.65)), 2)
        # Calibrate measurable grammar parameters from the uploaded pages.  The
        # values are clamped to the TitleDNA contract so a noisy scan can never
        # produce an invalid grid or unreadable body text.
        if features:
            columns = round(sum(float(c.get("columns", c.get("dominant_columns", dna.grid.columns))) for c in features) / len(features))
            gutter = sum(float(c.get("gutter_mm", dna.grid.gutter_mm)) for c in features) / len(features)
            baseline = sum(float(c.get("baseline_grid_pt", dna.grid.baseline_grid_pt)) for c in features) / len(features)
            dna.grid.columns = max(1, min(24, columns))
            dna.grid.gutter_mm = max(0.5, round(gutter, 2))
            dna.grid.baseline_grid_pt = max(3.0, round(baseline, 2))
            body = sum(float(c.get("body_size_pt", dna.typography.scales.body)) for c in features) / len(features)
            dna.typography.scales.body = max(6.5, round(body, 2))
            dna.typography.scales.caption = max(5.5, round(dna.typography.scales.body * 0.79, 2))
            dna.photo_rules.text_wrap_offset_mm = max(1.0, round(sum(float(c.get("photo_coverage", 0.3)) * 3.5 for c in features) / len(features), 2))
        dna.version += 1

    db.save_title_dna(project_id, dna)
    return dna
